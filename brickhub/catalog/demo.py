"""Demo shop content built from ``data/catalog_seed.json``.

All LEGO numbers, names, years and piece counts come from the official
catalogue.  Prices, stock levels and shop flags are DEMO values generated by
simple rules – change them in the admin panel or with a CSV/Excel import.
"""
