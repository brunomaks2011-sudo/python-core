SEED_FILE = Path(settings.BASE_DIR) / "data" / "catalog_seed.json"

PRICE_PER_PIECE = {
    "city": 3.7, "friends": 3.7, "creator": 3.4, "technic": 4.0, "icons": 3.8, "architecture": 4.6, "ideas": 4.0,
    "star-wars": 4.6, "marvel": 4.4, "harry-potter": 4.3, "ninjago": 4.0, "minecraft": 4.7, "super-mario": 5.4,
    "speed-champions": 4.8, "dc": 4.4, "disney": 4.4, "jurassic-world": 4.5, "botanicals": 3.6, "dreamzzz": 4.0,
    "lego-art": 3.2,
}
FIG_FACTOR = {"star-wars": 1.5, "marvel": 1.45, "dc": 1.35, "harry-potter": 1.3, "ninjago": 1.15,
              "collectible-minifigures": 1.2, "city": 0.9}


def _rng(key: str) -> random.Random:
    return random.Random(int(hashlib.sha256(key.encode()).hexdigest()[:12], 16))


def nice_price(value: float) -> Decimal:
    if value < 1000:
        v = max(99, round(value / 10) * 10 - 1)
    elif value < 10000:
        v = round(value / 50) * 50 - 1
    else:
        v = round(value / 100) * 100 - 1
    return Decimal(v)


def part_price(base: float, color: Color, used: bool = False) -> Decimal:
    factor = 1.0
    if color.is_transparent:
        factor = 1.15
    if color.finish in ("chrome", "metallic", "pearl", "glitter"):
        factor = 1.4
    if used:
        factor *= 0.6
    value = Decimal(str(base * factor)).quantize(Decimal("0.5"), rounding=ROUND_HALF_UP)
    return max(value, Decimal("1.00"))


def _theme_for_series(slug: str) -> Theme | None:
    return Theme.objects.filter(slug=slug).first()


def _ensure_reference(seed: dict):
    """Make sure colours / themes / part categories exist even without import_catalog."""
    if Color.objects.exists() and Theme.objects.exists():
        apply_structure()
        return
    from .importer import DEFAULT_FILE, import_bundle

    import_bundle(DEFAULT_FILE)


@transaction.atomic
def seed_demo(stdout=None, with_images: bool = False) -> dict:
    seed = json.loads(SEED_FILE.read_text(encoding="utf-8"))
    _ensure_reference(seed)
    now = timezone.now()
    cats = {c.slug: c for c in Category.objects.all()}
    colors = {c.rebrickable_id: c for c in Color.objects.filter(rebrickable_id__isnull=False)}
    themes_rb = {t.rebrickable_id: t for t in Theme.objects.filter(rebrickable_id__isnull=False)}
    stats = {"sets": 0, "parts": 0, "minifigs": 0, "accessories": 0}

    def image(product, url, alt):
        if with_images and url and not product.images.exists():
            ProductImage.objects.create(product=product, external_url=url, alt=alt)

    def stock(product, qty):
        inv, _ = Inventory.objects.get_or_create(product=product)
        if inv.quantity != qty:
            inv.quantity = qty
            inv.save()

    # ---------------- sets ----------------
    bestsellers = set()
    by_series = {}
    for s in seed["sets"]:
        by_series.setdefault(s["series"], []).append(s)
    for series, items in by_series.items():
        regular = [x for x in items if not x.get("rare") and not x.get("used_only")]
        for x in sorted(regular, key=lambda x: -x["pieces"])[:2]:
            bestsellers.add(x["number"])
    for idx, s in enumerate(seed["sets"]):
        theme = themes_rb.get(s["rb_theme"])
        series_theme = _theme_for_series(s["series"]) or theme
        lego_set, _ = LegoSet.objects.update_or_create(
            number=s["number"],
            defaults={"name": s["name"], "year": s["year"], "theme": theme, "pieces": s["pieces"],
                      "minifigs_count": s["minifigs"], "image_url": s["img_url"]},
        )
        rng = _rng(s["number"])
        base = s["pieces"] * PRICE_PER_PIECE.get(s["series"], 4.0) * (0.85 if s["pieces"] > 3000 else 1.0)
        base += s["minifigs"] * 30
        conditions = ["used"] if s.get("used_only") else ["new"]
        if not s.get("used_only") and not s.get("rare") and rng.random() < 0.12:
            conditions.append("used")
        for cond in conditions:
            price = base * (1.9 if s.get("rare") else 1.0) * (0.62 if cond == "used" else 1.0)
            product = Product.objects.filter(kind="set", lego_set=lego_set, condition=cond).first() or Product(
                kind="set", lego_set=lego_set, condition=cond)
            product.category = cats["nabory"]
            product.theme = series_theme
            product.price = nice_price(price)
            product.old_price = None
            if cond == "new" and not s.get("rare") and rng.random() < 0.14:
                product.old_price = nice_price(price * rng.choice([1.15, 1.2, 1.25]))
            product.is_new = cond == "new" and s["year"] >= 2025
            product.is_rare = bool(s.get("rare"))
            product.is_featured = cond == "new" and s["number"] in bestsellers
            product.is_bestseller = cond == "new" and (s["number"] in bestsellers or rng.random() < 0.12)
            product.completeness = (
                "Б/у: повний комплект деталей і мініфігурок, з інструкцією, без коробки" if cond == "used" else "")
            product.description = set_description(s, series_theme, cond)
            product.created_at = now - timedelta(days=(2026 - s["year"]) * 30 + rng.randint(0, 25),
                                                 hours=rng.randint(0, 23))
            product.save()
            image(product, s["img_url"], f"LEGO {s['number'].split('-')[0]} {s['name']}")
            if s.get("rare"):
                qty = rng.randint(1, 2)
            elif cond == "used":
                qty = 1
            else:
                qty = 0 if rng.random() < 0.08 else rng.randint(2, 14)
            stock(product, qty)
            stats["sets"] += 1

    # ---------------- accessories ----------------
    for a in seed["accessories"]:
        lego_set, _ = LegoSet.objects.update_or_create(
            number=a["number"],
            defaults={"name": a["name"], "year": a["year"], "theme": themes_rb.get(a["rb_theme"]),
                      "image_url": a["img_url"]},
        )
        rng = _rng(a["number"])
        low = a["name"].lower()
        price = 349 if "key chain" in low else 1299 if "display" in low else 899
        product = Product.objects.filter(kind="accessory", lego_set=lego_set).first() or Product(
            kind="accessory", lego_set=lego_set)
        product.category = cats["aksesuary"]
        product.price = Decimal(price)
        product.description = (
            f"Оригінальний аксесуар LEGO «{a['name']}» (арт. {a['number'].split('-')[0]}). "
            "Чудовий подарунок для фанатів LEGO та зручне доповнення до колекції.")
        product.is_new = a["year"] >= 2025
        product.created_at = now - timedelta(days=rng.randint(1, 200))
        product.save()
        image(product, a["img_url"], a["name"])
        stock(product, rng.randint(0, 9))
        stats["accessories"] += 1

    # ---------------- minifigures ----------------
    for m in seed["minifigs"]:
        series_theme = _theme_for_series(m["series"])
        contents = [{"part": c[0], "name": c[1], "color": colors[c[2]].name if c[2] in colors else "",
                     "qty": c[3]} for c in m["contents"]]
        fig, _ = Minifigure.objects.update_or_create(
            fig_number=m["fig_num"],
            defaults={"name": m["name"], "theme": series_theme, "year": m["year"], "num_parts": m["num_parts"],
                      "image_url": m["img_url"], "contents": contents, "appears_in": m["appears_in"],
                      "character": m["name"].split(",")[0].split(" - ")[0].strip()},
        )
        rng = _rng(m["fig_num"])
        base = (110 + 14 * (m["num_parts"] or 4)) * FIG_FACTOR.get(m["series"], 1.1)
        conditions = ["new"] + (["used"] if rng.random() < 0.25 else [])
        for cond in conditions:
            product = Product.objects.filter(kind="minifig", minifigure=fig, condition=cond).first() or Product(
                kind="minifig", minifigure=fig, condition=cond)
            product.category = cats["minifihurky"]
            product.theme = series_theme
            product.price = nice_price(base * (0.65 if cond == "used" else 1.0))
            product.completeness = "Повна комплектація, як у наборі" if cond == "new" else (
                "Б/у: без пошкоджень, можливі легкі сліди гри")
            product.is_featured = cond == "new" and m.get("set_count", 0) >= 4
            product.is_new = cond == "new" and (m["year"] or 0) >= 2025
            product.description = minifig_description(m, series_theme)
            product.created_at = now - timedelta(days=rng.randint(0, 160), hours=rng.randint(0, 23))
            product.save()
            image(product, m["img_url"], m["name"])
            stock(product, 0 if rng.random() < 0.1 else rng.randint(1, 6))
            stats["minifigs"] += 1

    # ---------------- parts ----------------
    valid_pc = set(PartCategory.objects.values_list("id", flat=True))
    for p in seed["parts"]:
        part, _ = Part.objects.update_or_create(
            design_id=p["design_id"],
            defaults={"name": p["name"], "name_uk": p["name_uk"], "category": cats[p["shop_category"]],
                      "part_category_id": p["rb_category"] if p["rb_category"] in valid_pc else None},
        )
        for rank, cid in enumerate(p["colors"]):
            color = colors.get(cid)
            if color is None:
                continue
            rng = _rng(f"{p['design_id']}-{cid}")
            conds = ["new"]
            if rank < 3 and p["shop_category"] in ("tsehlynky", "plastyny", "elementy-technic") and rng.random() < 0.5:
                conds.append("used")
            for cond in conds:
                product = Product.objects.filter(kind="part", part=part, color=color, condition=cond).first() or \
                    Product(kind="part", part=part, color=color, condition=cond)
                product.category = cats[p["shop_category"]]
                product.price = part_price(p["base_price"], color, used=cond == "used")
                product.is_featured = rank == 0 and p["set_count"] > 1500
                product.created_at = now - timedelta(days=rng.randint(0, 120), hours=rng.randint(0, 23))
                product.description = ""
                product.save()
                if rng.random() < 0.05:
                    qty = 0
                elif rank < 3:
                    qty = rng.randint(150, 2500)
                else:
                    qty = rng.randint(8, 600)
                if cond == "used":
                    qty = rng.randint(20, 300)
                stock(product, qty)
                stats["parts"] += 1

    # ---------------- promo codes ----------------
    promos = [
        ("WELCOME10", "Знижка 10% на перше замовлення від 500 ₴", "percent", 10, "all", 500, True),
        ("DETALI15", "−15% на окремі деталі від 300 ₴", "percent", 15, "part", 300, False),
        ("MINIFIG100", "−100 ₴ на мініфігурки від 800 ₴", "fixed", 100, "minifig", 800, False),
    ]
    for code, desc, kind, value, scope, min_total, once in promos:
        PromoCode.objects.get_or_create(code=code, defaults={
            "description": desc, "discount_type": kind, "value": value, "scope": scope,
            "min_order_total": min_total, "once_per_user": once})
    return stats


def set_description(s: dict, theme: Theme | None, cond: str) -> str:
    num = s["number"].split("-")[0]
    series = theme.display_name if theme else "LEGO"
    figs = s.get("minifigs") or 0
    text = [f"Оригінальний набір {series} «{s['name']}» (номер {num}) {s['year']} року випуску — "
            f"{s['pieces']} деталей для захопливого збирання."]
    if figs:
        text.append(f"У комплекті {figs} {plural(figs, 'мініфігурка', 'мініфігурки', 'мініфігурок')}.")
    if theme and theme.description:
        text.append(theme.description)
    if cond == "used":
        text.append("Набір б/у — стан і комплектацію вказано в характеристиках.")
    else:
        text.append("Новий набір у заводській упаковці.")
    return " ".join(text)


def minifig_description(m: dict, theme: Theme | None) -> str:
    series = theme.display_name if theme else "LEGO"
    text = [f"Оригінальна мініфігурка {series}: {m['name']}."]
    if m.get("appears_in"):
        sets = ", ".join(n.split("-")[0] for n in m["appears_in"][:4])
        text.append(f"Зустрічається в наборах: {sets}.")
    text.append("Комплектація — як у таблиці нижче (офіційні номери деталей).")
    return " ".join(text)


