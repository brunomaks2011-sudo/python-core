"""Modular building kit for destructible buildings.

Every wall module is 3 m wide, 2.75 m tall (3 m storey minus a 0.25 m slab) and
0.3 m thick. The OUTSIDE face points to Blender +Y (Roblox LookVector), the
piece origin is its centre. Openings are real gaps between parts, so bullets,
soldiers and debris go through windows and doors. Glass panes are separate
pieces so they can shatter independently (damage stage 2).

Styles: plaster (village houses, tinted per building at runtime), brick
(industrial), panel (apartment blocks), concrete (military/admin), metal
(warehouses/hangars, corrugated), wood (barns). Slabs, ring beams, parapets,
roof slopes and gables are simple boxes/wedges generated by the runtime
BuildingLayout from the same dimensions.
"""
from rbxlib import Model
from models.palette import GLASS, GUNMETAL, STEEL, WOOD, rgb

M, WH, T = 3.0, 2.75, 0.3
STYLES = {
    "plaster": dict(mat="Plaster", color=rgb(214, 204, 176), frame=rgb(236, 236, 230), frame_mat="SmoothPlastic", sill=rgb(160, 156, 150), shutters=True),
    "brick": dict(mat="Brick", color=rgb(150, 78, 58), frame=rgb(70, 74, 72), frame_mat="Metal", sill=rgb(150, 146, 140), shutters=False),
    "panel": dict(mat="Concrete", color=rgb(186, 184, 176), frame=rgb(225, 225, 220), frame_mat="SmoothPlastic", sill=rgb(140, 140, 136), shutters=False),
    "concrete": dict(mat="Concrete", color=rgb(164, 166, 158), frame=rgb(90, 94, 92), frame_mat="Metal", sill=rgb(130, 130, 126), shutters=False),
    "metal": dict(mat="CorrodedMetal", color=rgb(128, 138, 140), frame=rgb(80, 84, 86), frame_mat="Metal", sill=rgb(110, 114, 116), shutters=False),
    "wood": dict(mat="WoodPlanks", color=rgb(118, 88, 60), frame=rgb(90, 66, 44), frame_mat="Wood", sill=rgb(100, 76, 52), shutters=False),
}
OPENINGS = {
    # type: (opening width, opening height, sill height)
    "window": (1.2, 1.4, 0.9),
    "door": (1.1, 2.2, 0.0),
    "bigdoor": (2.6, 2.6, 0.0),
    "shopwindow": (2.6, 1.9, 0.5),
    "frenchwindow": (1.4, 2.2, 0.0),
}
GLASS_FOR = {"window": "glass_window", "shopwindow": "glass_shop", "frenchwindow": "glass_tall"}


def wall_block(m, st, name, size, at, mat=None, color=None):
    """Wall chunk; parts named Wall* are tinted per building."""
    return m.block(name, size, at, mat=mat or st["mat"], color=color or st["color"], collide=True)


def style_details(m, style, st, z0=-WH / 2):
    if style == "panel":
        m.block("Joint", (0.04, 0.02, WH), (M / 2 - 0.02, T / 2 + 0.005, 0), mat="Concrete", color=rgb(120, 118, 112))
        m.block("JointH", (M, 0.02, 0.04), (0, T / 2 + 0.005, z0 + 0.02), mat="Concrete", color=rgb(120, 118, 112))
    elif style == "metal":
        for k in range(6):
            m.block(f"Rib{k}", (0.07, 0.04, WH), (-M / 2 + 0.25 + k * 0.5, T / 2 + 0.02, 0), mat="CorrodedMetal", color=rgb(118, 128, 130))
    elif style == "wood":
        for k in range(4):
            m.block(f"Batten{k}", (0.06, 0.04, WH), (-M / 2 + 0.375 + k * 0.75, T / 2 + 0.02, 0), mat="Wood", color=rgb(100, 74, 50))
    elif style == "brick":
        m.block("Course", (M, 0.04, 0.12), (0, T / 2 + 0.02, WH / 2 - 0.2), mat="Brick", color=rgb(128, 64, 48))


def kit_wall(style):
    st = STYLES[style]
    m = Model(f"Kit_{style}_wall", "Buildings/Kit", "wall", {"Style": style, "Piece": "wall"})
    wall_block(m, st, "Wall", (M, T, WH), (0, 0, 0))
    style_details(m, style, st)
    return m


def kit_corner(style):
    st = STYLES[style]
    m = Model(f"Kit_{style}_corner", "Buildings/Kit", "corner", {"Style": style, "Piece": "corner"})
    wall_block(m, st, "WallCorner", (T, T, WH), (0, 0, 0), color=tuple(c * 0.92 for c in st["color"]))
    return m


def kit_opening(style, kind):
    st = STYLES[style]
    ow, oh, sill = OPENINGS[kind]
    m = Model(f"Kit_{style}_{kind}", "Buildings/Kit", kind, {"Style": style, "Piece": kind, "Glass": GLASS_FOR.get(kind, "")})
    z0 = -WH / 2
    side = (M - ow) / 2
    # jambs
    wall_block(m, st, "WallJambL", (side, T, WH), (-M / 2 + side / 2, 0, 0))
    wall_block(m, st, "WallJambR", (side, T, WH), (M / 2 - side / 2, 0, 0))
    if sill > 0:
        wall_block(m, st, "WallBelow", (ow, T, sill), (0, 0, z0 + sill / 2))
    top = WH - sill - oh
    if top > 0.02:
        wall_block(m, st, "WallAbove", (ow, T, top), (0, 0, z0 + sill + oh + top / 2))
    # frame
    fz = z0 + sill + oh / 2
    fm, fc = st["frame_mat"], st["frame"]
    m.block("FrameL", (0.08, 0.14, oh), (-ow / 2 + 0.04, 0.03, fz), mat=fm, color=fc)
    m.block("FrameR", (0.08, 0.14, oh), (ow / 2 - 0.04, 0.03, fz), mat=fm, color=fc)
    m.block("FrameTop", (ow, 0.14, 0.08), (0, 0.03, z0 + sill + oh - 0.04), mat=fm, color=fc)
    if kind in ("window", "shopwindow", "frenchwindow"):
        m.block("FrameBottom", (ow, 0.14, 0.08), (0, 0.03, z0 + sill + 0.04), mat=fm, color=fc)
        m.block("Mullion", (0.06, 0.1, oh), (0, 0.02, fz), mat=fm, color=fc)
    if kind == "window":
        m.block("Sill", (ow + 0.2, 0.22, 0.06), (0, T / 2 + 0.05, z0 + sill - 0.03), mat="Concrete", color=st["sill"])
        if st["shutters"]:
            for s in (-1, 1):
                m.block(f"Shutter{'R' if s > 0 else 'L'}", (0.55, 0.04, oh), (s * (ow / 2 + 0.3), T / 2 + 0.03, fz), mat="WoodPlanks", color=rgb(70, 96, 70))
    if kind == "door":
        m.group("Leaf", (-ow / 2 + 0.05, -T / 2, z0))
        m.block("DoorLeaf", (ow - 0.1, 0.05, oh - 0.05), (-ow / 2 + 0.05 + 0.03, -T / 2 - (ow - 0.1) / 2, z0 + (oh - 0.05) / 2), (0, 0, 90), "WoodPlanks", rgb(110, 76, 50), group="Leaf", collide=True)
        m.block("Step", (ow + 0.3, 0.4, 0.15), (0, T / 2 + 0.2, z0 + 0.075 - 0.15), mat="Concrete", color=st["sill"])
    if kind == "bigdoor":
        m.block("ShutterBox", (ow + 0.2, 0.35, 0.3), (0, -T / 2 - 0.15, z0 + oh - 0.1), mat="Metal", color=STEEL)
        m.block("Bollard", (0.2, 0.2, 0.9), (-ow / 2 - 0.2, T / 2 + 0.15, z0 + 0.45), mat="Metal", color=rgb(220, 180, 40))
    if kind == "frenchwindow":
        m.block("Threshold", (ow, 0.3, 0.05), (0, 0, z0 + 0.025), mat="Concrete", color=st["sill"])
    return m


def kit_glass(kind):
    sizes = {"glass_window": (1.12, 1.32), "glass_shop": (2.5, 1.82), "glass_tall": (1.32, 2.12)}
    w, h = sizes[kind]
    m = Model(f"Kit_{kind}", "Buildings/Kit", kind, {"Piece": kind, "Mat": "glass"})
    m.block("Pane", (w, 0.03, h), (0, 0, 0), mat="Glass", color=GLASS, transparency=0.55, collide=True)
    return m


def kit_interior(door):
    m = Model("Kit_int_door" if door else "Kit_int_wall", "Buildings/Kit", "int_door" if door else "int_wall", {"Piece": "int_door" if door else "int_wall"})
    c = rgb(206, 202, 192)
    if door:
        ow = 0.95
        side = (M - ow) / 2
        m.block("WallL", (side, 0.15, WH), (-M / 2 + side / 2, 0, 0), mat="Plaster", color=c, collide=True)
        m.block("WallR", (side, 0.15, WH), (M / 2 - side / 2, 0, 0), mat="Plaster", color=c, collide=True)
        m.block("WallAbove", (ow, 0.15, WH - 2.1), (0, 0, -WH / 2 + 2.1 + (WH - 2.1) / 2), mat="Plaster", color=c, collide=True)
    else:
        m.block("Wall", (M, 0.15, WH), (0, 0, 0), mat="Plaster", color=c, collide=True)
    return m


def kit_stairs():
    """One storey of stairs inside a 3 x 3 m module, rising toward +Y."""
    m = Model("Kit_stairs", "Buildings/Kit", "stairs", {"Piece": "stairs"})
    steps = 11
    run = 2.6 / steps
    rise = 3.0 / steps
    for k in range(steps):
        m.block(f"Step{k}", (1.3, run + 0.02, rise), (-0.75, -1.3 + run * (k + 0.5), -1.5 + rise * (k + 0.5)), mat="Concrete", color=rgb(150, 148, 142), collide=True)
    m.block("Stringer", (0.1, 3.6, 0.3), (-0.05, 0, -0.15), (45, 0, 0), "Concrete", rgb(140, 138, 132))
    m.block("Handrail", (0.05, 3.6, 0.05), (0.0, 0, 0.85), (45, 0, 0), "Metal", GUNMETAL)
    return m


def kit_balcony():
    m = Model("Kit_balcony", "Buildings/Kit", "balcony", {"Piece": "balcony"})
    m.block("Slab", (2.8, 1.2, 0.15), (0, 0.6, 0), mat="Concrete", color=rgb(170, 168, 160), collide=True)
    m.block("Front", (2.8, 0.06, 1.0), (0, 1.17, 0.55), mat="Concrete", color=rgb(178, 176, 168), collide=True)
    for s in (-1, 1):
        m.block(f"Side{'R' if s > 0 else 'L'}", (0.06, 1.1, 1.0), (s * 1.37, 0.6, 0.55), mat="Concrete", color=rgb(178, 176, 168), collide=True)
    m.block("Rail", (2.84, 0.08, 0.06), (0, 1.17, 1.07), mat="Metal", color=GUNMETAL)
    return m


def ENTRIES():
    out = []
    for style in STYLES:
        out.append((f"kit_{style}_wall", (lambda s=style: lambda: kit_wall(s))()))
        out.append((f"kit_{style}_corner", (lambda s=style: lambda: kit_corner(s))()))
        for kind in OPENINGS:
            out.append((f"kit_{style}_{kind}", (lambda s=style, k=kind: lambda: kit_opening(s, k))()))
    for g in ("glass_window", "glass_shop", "glass_tall"):
        out.append((f"kit_{g}", (lambda g=g: lambda: kit_glass(g))()))
    out += [("kit_int_wall", lambda: kit_interior(False)), ("kit_int_door", lambda: kit_interior(True)),
            ("kit_stairs", kit_stairs), ("kit_balcony", kit_balcony)]
    return out
